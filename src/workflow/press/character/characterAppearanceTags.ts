/** 由「组名 + [标签, 维度与要点] 列表」派生分组：要点只进悬停提示，不写进文档 */
function toTagGroups(
    source: readonly (readonly [string, readonly (readonly [string, string])[]])[],
): readonly TagGroup[] {
    return source.map(([label, items]) => ({
        label,
        options: items.map<TagOption>(([value, hint]) => ({ value, hint })),
    }))
}

