/** 标签分组的紧凑写法：只写组名与标签文本，TagOption 结构在此统一补全 */
function toTagGroups(source: readonly (readonly [string, readonly string[]])[]): readonly TagGroup[] {
    return source.map(([label, tags]) => ({ label, options: tags.map<TagOption>((tag) => ({ value: tag })) }))
}

